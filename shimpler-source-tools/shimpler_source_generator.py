"""Materialize resolved shim sources for Shimplify's Jython 2.7 task."""

import os
import re
import shutil

from shimpler_source_resolver import resolve_sources, scan_module_sources


SPARK_CLASSIFIER = '$_spark.version.classifier_'
PACKAGE_CLASSIFIER = re.compile('package .*(' + re.escape(SPARK_CLASSIFIER) + ')')


def generate_sources(module_root, generated_root, graph, target, valid_targets=None,
                     allowed_external_targets=()):
    """Replace Shimplify-owned main/test outputs with the target's selected sources.

    Selection and validation finish before old outputs are removed. The caller's
    cache marker is written only after this function succeeds, so an interrupted
    generation is retried by Maven.
    """
    # Other Scala POMs may define selectors that are inert in this build. Parse
    # against the repository-wide target set, but resolve using only this graph.
    variants, unannotated = scan_module_sources(
        module_root, graph if valid_targets is None else valid_targets,
        allowed_external_targets)
    if unannotated:
        raise ValueError('No shim selector block in %s' % unannotated[0])
    selected = resolve_sources(graph, variants, target)

    for scope in ('main', 'test'):
        scope_root = os.path.join(generated_root, scope)
        if os.path.islink(scope_root):
            raise ValueError('Generated source directory is a symlink: %s' % scope_root)
        if os.path.isdir(scope_root):
            shutil.rmtree(scope_root)

    for logical in sorted(selected):
        source = selected[logical].physical_path
        destination = os.path.join(generated_root, *logical.split('/')[1:])
        parent = os.path.dirname(destination)
        if not os.path.isdir(parent):
            os.makedirs(parent)
        with open(source, 'r') as source_file:
            contents = source_file.read()
        match = PACKAGE_CLASSIFIER.search(contents)
        if match is None:
            os.symlink(os.path.abspath(source), destination)
        else:
            with open(destination, 'w') as output:
                output.write(contents[:match.start(1)])
                output.write('spark' + target)
                output.write('\n')
                output.write('''
/*
!!! DO NOT EDIT THIS FILE !!!

This file has been generated from the original

%s

by interpolating $_spark.version.classifier_=%s

Be sure to edit the original file if required

*/
                ''' % (source, 'spark' + target))
                output.write(contents[match.end(1):])
    return selected
